"""Evaluate the query parser and the ranking logic on hand-labelled cases.

Usage (from the repo root):
    python -m ml.evaluation.run_eval            # print report
    python -m ml.evaluation.run_eval --write    # also write docs/evaluation_report.md

Parser: exact match on each field; a query is "correct" only if ALL fields match.
Ranking: top-1 accuracy and mean reciprocal rank (MRR) of the expected place.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from ml.api import parse_location_query, rank_results

HERE = Path(__file__).resolve().parent
REPORT_PATH = HERE.parents[1] / "docs" / "evaluation_report.md"
FIELDS = ["name", "category", "reference", "relation", "radius_km", "use_user_location"]


def _norm(field: str, value):
    if isinstance(value, str):
        value = value.strip().lower()
    if field == "radius_km" and value is not None:
        return round(float(value), 2)
    return value


def load_queries() -> list[dict]:
    return [json.loads(line) for line in (HERE / "parser_queries.jsonl").read_text().splitlines() if line.strip()]


def eval_parser(rows: list[dict]) -> dict:
    per_field = {f: 0 for f in FIELDS}
    exact = 0
    failures = []
    for row in rows:
        got = parse_location_query(row["q"])
        wrong = [f for f in FIELDS if _norm(f, got[f]) != _norm(f, row[f])]
        for f in FIELDS:
            per_field[f] += f not in wrong
        if wrong:
            failures.append({"q": row["q"], "tier": row["tier"], "wrong": {f: {"expected": row[f], "got": got[f]} for f in wrong}})
        else:
            exact += 1
    n = len(rows)
    return {
        "n": n,
        "exact": exact,
        "exact_acc": exact / n,
        "per_field": {f: per_field[f] / n for f in FIELDS},
        "failures": failures,
    }


def eval_ranking(cases: list[dict]) -> dict:
    top1 = 0
    rr_sum = 0.0
    failures = []
    for c in cases:
        parsed = parse_location_query(c["query"])
        ref = c["ref"] or (None, None)
        ranked = rank_results(parsed, c["candidates"], ref[0], ref[1], limit=len(c["candidates"]))
        order = [r["id"] for r in ranked]
        if c["expected_top"] in order:
            rank = order.index(c["expected_top"]) + 1
            rr_sum += 1 / rank
        else:
            rank = None
        if rank == 1:
            top1 += 1
        else:
            failures.append({"id": c["id"], "expected": c["expected_top"], "got_order": order})
    n = len(cases)
    return {"n": n, "top1": top1 / n, "mrr": rr_sum / n, "failures": failures}


TIER_NOTES = {
    "core": "Typical queries used while writing the parser. Optimistic: the rules were written against them.",
    "hard": "Known weak spots found by the first evaluation (typos, word order, price/hours phrases, "
            "conversational). Fixes were written while looking at these, so this tier is tuned too.",
    "heldout": "Written after the first fixes and scored once. Later fixes (nearest/ATM, brand names) targeted its "
               "two misses, so it is now a regression set, not an unseen estimate.",
    "hinglish_dev": "Hinglish / Indian-style queries the Hinglish rules were tuned on. Optimistic.",
    "heldout2": "Hinglish and 'nearest' queries scored once after the Hinglish fixes. CAVEAT: written by the same "
                "author in the same session as the fixes, so it is NOT truly unseen and 100% here is optimistic. "
                "Real estimate needs queries written by someone else.",
}


def build_report(parser: dict[str, dict], ranking: dict) -> str:
    pct = lambda x: f"{x * 100:.1f}%"
    all_ = parser["all"]
    lines = [
        "# Evaluation report",
        "",
        "Generated by `python -m ml.evaluation.run_eval --write`. Test data lives in `ml/evaluation/`.",
        "",
        "> Hand-written cases, not a public benchmark. Read the tier notes below before quoting a number.",
        "",
        "## Query parser",
        "",
        "| Tier | Queries | All fields correct |",
        "|---|---|---|",
    ]
    for tier in ("core", "hard", "heldout", "hinglish_dev", "heldout2", "all"):
        if tier in parser:
            r = parser[tier]
            lines.append(f"| {tier} | {r['n']} | {r['exact']} ({pct(r['exact_acc'])}) |")
    lines += ["", "Tier notes:", ""]
    lines += [f"- **{t}**: {note}" for t, note in TIER_NOTES.items() if t in parser]
    lines += ["", "Per-field accuracy (all queries):", "", "| Field | Accuracy |", "|---|---|"]
    lines += [f"| {f} | {pct(a)} |" for f, a in all_["per_field"].items()]
    lines += ["", "### Parser failures", ""]
    if all_["failures"]:
        for fl in all_["failures"]:
            detail = "; ".join(f"{f}: expected `{v['expected']}`, got `{v['got']}`" for f, v in fl["wrong"].items())
            lines.append(f"- [{fl['tier']}] `{fl['q']}` — {detail}")
    else:
        lines.append("None.")
    lines += [
        "",
        "## Ranking",
        "",
        "Synthetic candidates written by hand; shows the scoring behaves sensibly, not real-world quality.",
        "",
        f"- Cases: {ranking['n']}",
        f"- Top-1 accuracy: {pct(ranking['top1'])}",
        f"- MRR: {ranking['mrr']:.3f}",
        "",
        "### Ranking failures",
        "",
    ]
    if ranking["failures"]:
        lines += [f"- `{f['id']}`: expected `{f['expected']}` first, got order {f['got_order']}" for f in ranking["failures"]]
    else:
        lines.append("None.")
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true", help=f"write {REPORT_PATH.relative_to(HERE.parents[1])}")
    args = ap.parse_args()

    rows = load_queries()
    parser = {"all": eval_parser(rows)}
    for tier in ("core", "hard", "heldout", "hinglish_dev", "heldout2"):
        subset = [r for r in rows if r["tier"] == tier]
        if subset:
            parser[tier] = eval_parser(subset)
    ranking = eval_ranking(json.loads((HERE / "ranking_cases.json").read_text()))

    report = build_report(parser, ranking)
    print(report)
    if args.write:
        REPORT_PATH.write_text(report)
        print(f"written: {REPORT_PATH}")


if __name__ == "__main__":
    main()
